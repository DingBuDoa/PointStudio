"""Check the portable copy with a system-only PATH and leave it clean."""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
RELEASE = ROOT / 'PointStudio-1.0.1'
REPORTS = ROOT / 'tests/artifacts/release-verification'


def main():
    REPORTS.mkdir(parents=True, exist_ok=True)
    python = RELEASE / 'runtime/python/python.exe'
    system = Path(os.environ.get('SystemRoot', 'C:/Windows'))
    environment = os.environ.copy()
    environment.pop('PYTHONHOME', None)
    environment['PYTHONPATH'] = ''
    environment['PYTHONIOENCODING'] = 'utf-8'
    environment['QT_QPA_PLATFORM'] = 'offscreen'
    environment.pop('QT_PLUGIN_PATH', None)
    environment.pop('QT_QPA_PLATFORM_PLUGIN_PATH', None)
    environment['PATH'] = os.pathsep.join(map(str, (RELEASE / 'runtime/cuda', system / 'System32', system, system / 'System32/Wbem')))
    checks = []

    def run(name, args, extra_path=None):
        env = dict(environment)
        if extra_path: env['PATH'] = str(extra_path) + os.pathsep + env['PATH']
        completed = subprocess.run(list(map(str, args)), cwd=RELEASE, env=env, capture_output=True,
                                   text=True, encoding='utf-8', errors='replace', timeout=60,
                                   creationflags=subprocess.CREATE_NO_WINDOW if os.name == 'nt' else 0)
        output = completed.stdout + completed.stderr
        (REPORTS / (name + '.log')).write_text(output, encoding='utf-8')
        if completed.returncode:
            raise RuntimeError(f'{name}: exit {completed.returncode}; see {REPORTS / (name + ".log")}')
        checks.append(dict(name=name, status='pass'))
        print(name, 'PASS', flush=True)
        return output

    code = '''
from pathlib import Path
import sys
root=Path.cwd()
assert Path(sys.executable).is_relative_to(root)
import paths, PySide6, numpy, torch
assert paths.ROOT == root
for module in (paths, PySide6, numpy, torch):
    assert Path(module.__file__).is_relative_to(root), module.__file__
sys.path.insert(0,str(root/'runtime/fastmap'))
import fastmap.io, fastmap.memory_policy
assert Path(fastmap.io.__file__).is_relative_to(root)
assert torch.cuda.is_available()
assert (torch.ones(1,device='cuda:0')+1).item()==2
print('LOCAL_RUNTIME_PASS',sys.version.split()[0],PySide6.__version__,torch.__version__)
'''
    run('python-qt-pytorch-cuda', [python, '-B', '-c', code])
    run('ffmpeg', [RELEASE / 'runtime/ffmpeg/ffmpeg.exe', '-version'])
    run('colmap', [RELEASE / 'runtime/colmap/colmap.exe', '-h'], RELEASE / 'runtime/colmap')
    run('glomap', [RELEASE / 'runtime/glomap-gpu/glomap.exe', '-h'], RELEASE / 'runtime/glomap-gpu')
    run('glomap-cpu', [RELEASE / 'runtime/colmap/glomap.exe', '-h'], RELEASE / 'runtime/colmap')
    run('glomap-cudss', [RELEASE / 'runtime/glomap-gpu/gpu_solver_probe.exe'], RELEASE / 'runtime/glomap-gpu')
    launcher_log = RELEASE / 'logs/launcher.log'
    if launcher_log.exists(): raise FileExistsError('Expected a pristine release log directory')
    try:
        run('qt-launcher', [python, '-B', RELEASE / 'app/launch.py', '--check-ui'])
        text = launcher_log.read_text(encoding='utf-8')
        (REPORTS / 'qt-launcher.log').write_text(text, encoding='utf-8')
        if 'QT_UI_PASS' not in text or 'Traceback' in text:
            raise RuntimeError('Qt launcher did not report a successful startup')
    finally:
        # Remove only the diagnostic file generated by this check, never user files.
        if launcher_log.is_file() and launcher_log.resolve().parent == (RELEASE / 'logs').resolve():
            launcher_log.unlink()
    manifest = json.loads((RELEASE / 'RELEASE-MANIFEST.json').read_text(encoding='utf-8'))
    expected = {item['path'] for item in manifest['files']}
    actual = {path.relative_to(RELEASE).as_posix() for path in RELEASE.rglob('*') if path.is_file()}
    assert actual == expected | {'RELEASE-MANIFEST.json'}, (actual-expected, expected-actual)
    for item in manifest['files']:
        path = RELEASE / item['path']
        assert path.stat().st_size == item['bytes'], item['path']
        with path.open('rb') as stream:
            assert hashlib.file_digest(stream, 'sha256').hexdigest() == item['sha256'], item['path']
    for filename in ('task-queue.json', 'task-history.json'):
        assert json.loads((RELEASE / 'config' / filename).read_text(encoding='utf-8')) == []
    settings = json.loads((RELEASE / 'config/settings.json').read_text(encoding='utf-8'))
    assert settings['python'] == 'runtime/python/python.exe' and settings['output_root'] == 'output'
    assert not any((RELEASE / 'logs').iterdir()) and not any((RELEASE / 'output').iterdir())
    checks.append(dict(name='clean-package-and-sha256', status='pass'))
    result = dict(status='pass', directory=str(RELEASE), files=manifest['file_count'] + 1,
                  payload_gib=round(manifest['total_bytes']/2**30, 3), checks=checks,
                  validation_environment='system-only PATH plus bundled component DLL directories')
    (REPORTS / 'report.json').write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps(result, ensure_ascii=False), flush=True)


if __name__ == '__main__': main()
